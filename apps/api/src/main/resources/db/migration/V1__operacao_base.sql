-- Cria a tabela e define as colunas persistidas por este domínio.
create table tb_uf
(
    id_uf bigint generated by default as identity,
    cd_uf integer not null,
    sg_uf varchar(2) not null,
    no_uf varchar(60) not null,
    st_ativo varchar(1) not null default '1',

    constraint pk_tb_uf primary key (id_uf),
    constraint uk_tb_uf__cd_uf unique (cd_uf),
    constraint uk_tb_uf__sg_uf unique (sg_uf),
    constraint ck_tb_uf__st_ativo check (st_ativo in ('0','1'))
);

-- Cria a tabela e define as colunas persistidas por este domínio.
create table tb_unidade
(
    id_unidade bigint generated by default as identity,
    cd_unidade_epol bigint,
    sg_unidade varchar(50) not null,
    no_unidade varchar(255) not null,
    id_uf_fk bigint,
    cd_siorg_unidade bigint,
    st_fronteira varchar(1),
    st_ativo varchar(1) not null default '1',

    constraint pk_tb_unidade primary key (id_unidade),
    constraint uk_tb_unidade__cd_unidade_epol unique (cd_unidade_epol),
    constraint uk_tb_unidade__sg_unidade unique (sg_unidade),
    constraint fk_tb_unidade__tb_uf foreign key (id_uf_fk) references tb_uf (id_uf),
    constraint ck_tb_unidade__st_fronteira check (st_fronteira is null or st_fronteira in ('0','1')),
    constraint ck_tb_unidade__st_ativo check (st_ativo in ('0','1'))
);

-- Cria a tabela e define as colunas persistidas por este domínio.
create table tb_area_atribuicao
(
