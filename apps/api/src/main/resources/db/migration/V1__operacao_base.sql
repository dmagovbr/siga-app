    st_ativo varchar(1) not null default '1',

    constraint pk_tb_area_atribuicao primary key (id_area_atribuicao),
    constraint uk_tb_area_atribuicao__cd_epol unique (cd_area_atribuicao_epol),
    constraint fk_tb_area_atribuicao__tb_unidade foreign key (id_unidade_fk) references tb_unidade (id_unidade),
    constraint ck_tb_area_atribuicao__st_ativo check (st_ativo in ('0','1'))
);

